"""
基础工具函数：所有技能共享的状态构造和信号提取逻辑。
"""

from typing import Optional, Dict, Any


def build_minimal_agent_state(
    ticker: str,
    end_date: str,
    api_key: Optional[str] = None,
    start_date: Optional[str] = None,
) -> Dict[str, Any]:
    """
    构造最小化的 AgentState，用于调用原始分析师节点。
    这样既能复用现有逻辑，又不必在外部构造庞大的状态对象。
    
    Args:
        ticker: 股票代码，如 "AAPL"
        end_date: 分析截止日期，格式 "YYYY-MM-DD"
        api_key: Financial Datasets API Key（可选）
        start_date: 开始日期（可选，原始节点内部会自动计算）
    
    Returns:
        最小化的 AgentState 字典
    """
    return {
        "data": {
            "tickers": [ticker],
            "end_date": end_date,
            "start_date": start_date,  # 原始节点内部会补齐
            "portfolio": {"cash": 0.0, "positions": {}},
            "analyst_signals": {},
            "metadata": {"show_reasoning": False},
            "current_prices": {},
        },
        # 注入 API Key，以便原始节点中的 get_api_key_from_state 读取
        "api_keys": {"FINANCIAL_DATASETS_API_KEY": api_key},
        # 🆕 原始 warren_buffett_agent 需要从顶层读取 metadata
        "metadata": {"show_reasoning": False},
        # 技术分析师需要 messages 字段
        "messages": [],
    }


def extract_signal_from_state(
    result_state: Dict[str, Any],
    agent_id: str,
    ticker: str
) -> Dict[str, Any]:
    """
    从调用完分析师节点后返回的 state 中提取标准信号。
    所有大师分析师输出的信号都存储在 data.analyst_signals[agent_id][ticker] 中。
    """
    signals = (
        result_state
        .get("data", {})
        .get("analyst_signals", {})
        .get(agent_id, {})
        .get(ticker)
    )
    
    if not signals:
        return {
            "signal": "neutral",
            "confidence": 0.0,
            "reasoning": "No signal generated by the skill."
        }
    
    return {
        "signal": signals.get("signal", "neutral"),
        "confidence": signals.get("confidence", 0.0),
        "reasoning": signals.get("reasoning", ""),
    }