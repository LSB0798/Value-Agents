"""
基础工具函数：所有技能共享的状态构造和信号提取逻辑。
"""

from typing import Optional, Dict, Any


def build_minimal_agent_state(
    ticker: str,
    end_date: str,
    api_key: Optional[str] = None,
    start_date: Optional[str] = None,
    skill_workflow: Optional[str] = None,
) -> Dict[str, Any]:
    """
    构造最小化的 AgentState，用于调用原始分析师节点。
    skill_workflow: SKILL.md 的 Workflow 文本，会随 state 传给原始 agent，
                    由原始 agent 注入到最终决策 prompt。
    """
    return {
        "data": {
            "tickers": [ticker],
            "end_date": end_date,
            "start_date": start_date,
            "portfolio": {"cash": 0.0, "positions": {}},
            "analyst_signals": {},
            "metadata": {"show_reasoning": False},
            "current_prices": {},
            "skill_workflow": skill_workflow or "",
        },
        "api_keys": {"FINANCIAL_DATASETS_API_KEY": api_key},
        "metadata": {"show_reasoning": False},
    }


def extract_signal_from_state(
    result_state: Dict[str, Any],
    agent_id: str,
    ticker: str
) -> Dict[str, Any]:
    """
    从调用完分析师节点后返回的 state 中提取标准信号。
    所有大师分析师输出的信号都存储在 data.analyst_signals[agent_id][ticker] 中。
    """
    signals = (
        result_state
        .get("data", {})
        .get("analyst_signals", {})
        .get(agent_id, {})
        .get(ticker)
    )
    
    if not signals:
        return {
            "signal": "neutral",
            "confidence": 0.0,
            "reasoning": "No signal generated by the skill."
        }
    
    return {
        "signal": signals.get("signal", "neutral"),
        "confidence": signals.get("confidence", 0.0),
        "reasoning": signals.get("reasoning", ""),
    }