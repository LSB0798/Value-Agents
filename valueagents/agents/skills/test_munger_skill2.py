class TestMungerSkillUnit(unittest.TestCase):
    """单元测试：模拟外部依赖"""

    def setUp(self):
        # 使用临时缓存避免污染真实缓存
        self.temp_cache_dir = tempfile.mkdtemp()
        self.original_cache_dir = os.environ.get("VALUEAGENTS_CACHE_DIR")
        os.environ["VALUEAGENTS_CACHE_DIR"] = self.temp_cache_dir

    def tearDown(self):
        if os.path.exists(self.temp_cache_dir):
            shutil.rmtree(self.temp_cache_dir)
        if self.original_cache_dir is not None:
            os.environ["VALUEAGENTS_CACHE_DIR"] = self.original_cache_dir
        else:
            os.environ.pop("VALUEAGENTS_CACHE_DIR", None)

    @patch('valueagents.agents.skills.munger_skill.skill.charlie_munger_agent')
    def test_execute_returns_json(self, mock_agent):
        mock_agent.return_value = {
            "data": {
                "analyst_signals": {
                    "munger_skill": {
                        "BRK.B": {
                            "signal": "bullish",
                            "confidence": 78,
                            "reasoning": "Munger style reasoning"
                        }
                    }
                }
            }
        }
        result = execute(ticker="BRK.B", end_date="2026-06-30", api_key="fake_key")
        data = json.loads(result)
        self.assertIn("ticker", data)
        self.assertEqual(data["ticker"], "BRK.B")
        self.assertIn("signal", data)
        self.assertIn("confidence", data)
        self.assertIn("reasoning", data)
        self.assertIsInstance(data["confidence"], int)
        self.assertIn(data["signal"], ["bullish", "bearish", "neutral"])

    @patch('valueagents.agents.skills.munger_skill.skill.charlie_munger_agent')
    def test_execute_fallback_on_missing_signal(self, mock_agent):
        mock_agent.return_value = {"data": {"analyst_signals": {}}}
        result = execute(ticker="BRK.B", end_date="2026-06-30", api_key="fake_key")
        data = json.loads(result)
        self.assertEqual(data["signal"], "neutral")
        self.assertEqual(data["confidence"], 0.0)  # extract_signal_from_state 返回 float 0.0
        self.assertIn("No signal generated", data["reasoning"])

    @patch('valueagents.agents.skills.munger_skill.skill.charlie_munger_agent')
    def test_execute_exception_handling(self, mock_agent):
        mock_agent.side_effect = ValueError("SEC ticker not found")
        result = execute(ticker="INVALID", end_date="2026-06-30", api_key="fake_key")
        data = json.loads(result)
        self.assertEqual(data["signal"], "neutral")
        self.assertEqual(data["confidence"], 0)
        self.assertIn("Analysis failed", data["reasoning"])

    def test_build_minimal_agent_state(self):
        state = build_minimal_agent_state("BRK.B", "2026-06-30", api_key="test_key")
        self.assertEqual(state["data"]["tickers"], ["BRK.B"])
        self.assertEqual(state["data"]["end_date"], "2026-06-30")
        self.assertEqual(state["api_keys"]["FINANCIAL_DATASETS_API_KEY"], "test_key")
        self.assertEqual(state["metadata"]["show_reasoning"], False)

    def test_extract_signal_from_state(self):
        state = {
            "data": {
                "analyst_signals": {
                    "munger_skill": {
                        "BRK.B": {
                            "signal": "bearish",
                            "confidence": 30,
                            "reasoning": "Overvalued by Munger standards"
                        }
                    }
                }
            }
        }
        signal = extract_signal_from_state(state, "munger_skill", "BRK.B")
        self.assertEqual(signal["signal"], "bearish")
        self.assertEqual(signal["confidence"], 30)
        self.assertEqual(signal["reasoning"], "Overvalued by Munger standards")

        state["data"]["analyst_signals"] = {}
        signal = extract_signal_from_state(state, "munger_skill", "BRK.B")
        self.assertEqual(signal["signal"], "neutral")
        self.assertEqual(signal["confidence"], 0.0)
        self.assertEqual(signal["reasoning"], "No signal generated by the skill.")


class TestMungerSkillLoader(unittest.TestCase):
    def setUp(self):
        self.skill_dir = Path(__file__).parent / "munger_skill"
        if not self.skill_dir.exists():
            self.skill_dir = Path(__file__).parent.parent / "munger_skill"

    def test_loader_loads_skill(self):
        tool = load_skill(self.skill_dir)
        self.assertIsNotNone(tool)
        self.assertEqual(tool.name, "charlie_munger_analyst")
        self.assertIn("Munger", tool.description)
        args_schema = tool.args_schema
        self.assertIsNotNone(args_schema)
        self.assertIn("ticker", args_schema.model_fields)
        self.assertIn("end_date", args_schema.model_fields)
        self.assertIn("api_key", args_schema.model_fields)
        self.assertTrue(args_schema.model_fields["api_key"].is_required() is False)

    def test_loader_invalid_skill_ignored(self):
        with tempfile.TemporaryDirectory() as tmpdir:
            tmp_path = Path(tmpdir)
            (tmp_path / "SKILL.md").write_text("---\nname: test\n---", encoding="utf-8")
            tool = load_skill(tmp_path)
            self.assertIsNone(tool)


class TestMungerSkillIntegration(unittest.TestCase):
    """集成测试：使用真实数据源（需要启用 USE_EDGAR 或 USE_YFINANCE）"""
    @classmethod
    def setUpClass(cls):
        use_yfinance = os.environ.get("USE_YFINANCE", "false").lower() == "true"
        use_edgar = os.environ.get("USE_EDGAR", "false").lower() == "true"
        has_api_key = bool(os.environ.get("FINANCIAL_DATASETS_API_KEY"))
        if not (use_yfinance or use_edgar or has_api_key):
            raise unittest.SkipTest("No data source available (set USE_YFINANCE, USE_EDGAR, or FINANCIAL_DATASETS_API_KEY)")

    def test_real_execute_aapl(self):
        """真实执行 AAPL 分析，验证返回结构和合理性"""
        result_str = execute(ticker="AAPL", end_date="2026-06-30", api_key=None)
        data = json.loads(result_str)
        self.assertEqual(data["ticker"], "AAPL")
        self.assertIn(data["signal"], ["bullish", "bearish", "neutral"])
        self.assertIsInstance(data["confidence"], int)
        self.assertTrue(0 <= data["confidence"] <= 100)
        self.assertIsInstance(data["reasoning"], str)
        self.assertTrue(len(data["reasoning"]) > 0)

    def test_real_execute_brk_b(self):
        """真实执行 BRK.B 分析（Munger 喜欢的标的）"""
        result_str = execute(ticker="BRK.B", end_date="2026-06-30", api_key=None)
        data = json.loads(result_str)
        self.assertEqual(data["ticker"], "BRK.B")
        self.assertIn(data["signal"], ["bullish", "bearish", "neutral"])
        self.assertIsInstance(data["confidence"], int)

    def test_real_execute_invalid_ticker(self):
        """使用无效 ticker 应返回中性信号且 confidence 为 0（异常捕获）"""
        result_str = execute(ticker="INVALID", end_date="2026-06-30", api_key=None)
        data = json.loads(result_str)
        self.assertEqual(data["ticker"], "INVALID")
        self.assertEqual(data["signal"], "neutral")
        self.assertEqual(data["confidence"], 0)
        self.assertIn("Analysis failed", data["reasoning"])

    def test_loader_invoke(self):
        """通过 loader 加载的工具调用与直接 execute 一致"""
        skill_dir = Path(__file__).parent / "munger_skill"
        if not skill_dir.exists():
            skill_dir = Path(__file__).parent.parent / "munger_skill"
        tool = load_skill(skill_dir)
        self.assertIsNotNone(tool)
        result_str = tool.invoke({"ticker": "AAPL", "end_date": "2026-06-30", "api_key": None})
        data = json.loads(result_str)
        self.assertEqual(data["ticker"], "AAPL")
        self.assertIn(data["signal"], ["bullish", "bearish", "neutral"])


class TestMungerSkillCache(unittest.TestCase):
    """缓存测试：检查真实缓存目录中的核心文件（不修改存储位置）"""
    @classmethod
    def setUpClass(cls):
        use_yfinance = os.environ.get("USE_YFINANCE", "false").lower() == "true"
        use_edgar = os.environ.get("USE_EDGAR", "false").lower() == "true"
        if not (use_yfinance or use_edgar):
            raise unittest.SkipTest("Need USE_YFINANCE or USE_EDGAR to test disk cache")
        from valueagents.default_config import DEFAULT_CONFIG
        cls.cache_root = Path(DEFAULT_CONFIG["data_cache_dir"])
        if not cls.cache_root.exists():
            raise unittest.SkipTest(f"Cache root {cls.cache_root} does not exist")

    def test_cache_files_exist(self):
        """验证当前缓存中已存在 Munger 所需的核心文件（不创建新文件）"""
        ticker = "AAPL"
        # Munger 使用 annual 数据，检查 EDGAR 和 annual line_items
        edgar_file = self.cache_root / "fundamentals" / "edgar" / f"{ticker}_edgar.json"
        line_item_file = self.cache_root / "line_items" / f"{ticker}_annual_line_items.json"
        # 内幕交易和新闻缓存不是必需的（有 fallback），但也可以检查
        # 只检查核心财务数据
        self.assertTrue(edgar_file.exists() and edgar_file.stat().st_size > 0,
                        f"EDGAR cache file {edgar_file} missing or empty")
        self.assertTrue(line_item_file.exists() and line_item_file.stat().st_size > 0,
                        f"Line items cache file {line_item_file} missing or empty")

    def test_cache_reuse(self):
        """第二次调用应正常执行（使用缓存）"""
        ticker = "AAPL"
        try:
            execute(ticker=ticker, end_date="2026-06-30", api_key=None)
        except Exception as e:
            self.fail(f"First execution failed: {e}")
        try:
            execute(ticker=ticker, end_date="2026-06-30", api_key=None)
        except Exception as e:
            self.fail(f"Second execution failed: {e}")


if __name__ == "__main__":
    unittest.main(verbosity=2)
